    ASK_PHONE_NUMBER = "ask_phone_number"
    DIALING_NOW = "dialing_now"
    DIAL_FAILED = "dial_failed"

    # Bridge
    CONNECTED = "connected"
    PEER_HUNG_UP = "peer_hung_up"
    GOODBYE = "goodbye"


