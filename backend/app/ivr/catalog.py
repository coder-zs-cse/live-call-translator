def speak_digits(digits: str) -> str:
    """Space out digits so a TTS voice reads 1282 as four numbers, not one.

    Without this a room code is spoken as "one thousand two hundred and
    eighty-two", which nobody can write down or repeat back.
    """
    return " ".join(digits)
