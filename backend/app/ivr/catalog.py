    # Main menu
    MAIN_MENU = "main_menu"
    INVALID_CHOICE = "invalid_choice"

    # Room pairing
    ROOM_CODE_IS = "room_code_is"
    WAITING_FOR_PEER = "waiting_for_peer"
    ASK_ROOM_CODE = "ask_room_code"
    ROOM_NOT_FOUND = "room_not_found"
    NOBODY_JOINED = "nobody_joined"

